import { Lightbulb, MessagesSquare, Compass, BookOpen, Sparkles, type LucideIcon } from "lucide-react";

/**
 * The "Second Brain" content model.
 * Each category is anchored to a 3D position on/near the brain surface so the
 * scene and the UI stay in sync. Items are AI-surfaced in production; here they
 * are seeded, realistic, and mutable from the capture bar.
 */
export type BrainCategoryId = "ideas" | "thoughts" | "next" | "knowledge" | "insights";

export interface BrainCategory {
  id: BrainCategoryId;
  label: string;
  icon: LucideIcon;
  color: string;          // hex, drives the 3D node + UI accents
  blurb: string;
  anchor: [number, number, number]; // world position of the 3D marker
  phase: number;          // pulse offset
}

