export type BrainItemKind = "idea" | "thought" | "task" | "note" | "insight";

export interface BrainItem {
  id: string;
  category: BrainCategoryId;
  kind: BrainItemKind;
  /** Present on user-captured items; seeded items resolve text from i18n. */
  title?: string;
  detail?: string;
  done?: boolean;
  ts?: string;
  ai?: boolean;           // surfaced/generated by the AI
}

